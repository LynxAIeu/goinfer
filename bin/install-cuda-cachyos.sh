# ----------------------------------------------------------------------
# config_add – Add/update a key=value pair or ensure a flag token.
#
# Usage: config_add PARAM TOKEN FILE
#   If TOKEN contains '=', it is treated as a pair; otherwise as a flag.
#   The function does nothing if no line starts with PARAM (after whitespace).
#
# Perl scripts (must be in the same directory):
#   config_add.pl  – add/update a key=value pair or ensure a flag token
#   config_rm.pl   – remove a token
#   config.pm      – shared parsing/reconstruction module
#
# CONSTRAINTS (apply to both functions):
#   - The configuration file must use one of the formats:
#       PARAM="value token ..."
#       PARAM='value token ...'
#       PARAM=(value token ...)
#       PARAM[n]="value token ..."
#       PARAM[n]='value token ...'
#   - Tokens are whitespace‑separated.
#   - $param and $token are expected to be alphanumeric (protected by \Q...\E).
#   - Only lines starting with $param (after optional whitespace) are edited.
#   - Already‑commented lines (starting with '#') are ignored.
#   - The scripts are idempotent: they do not change a line if the desired
#     state already exists.
#   - A backup file is created on every invocation (via perl -i).
# ----------------------------------------------------------------------
config_add() {
    local param="$1" token="$2" file="$3"

    # Only proceed if at least one line starts with the parameter.
    if rg -q "^\s*$param\b" "$file"; then
        local suffix=".backup.$(date +%F_%H%M%S_%N)"
        $sudo perl -i"$suffix" -s -I "$dir" "$dir/config_add.pl" \
            -- -param="$param" -token="$token" "$file"
    fi
}

# ----------------------------------------------------------------------
# config_rm – Remove a token from lines that start with a parameter.
#
# Usage: config_rm PARAM TOKEN FILE
#   The function does nothing if no line starts with PARAM (after whitespace)
#   or if TOKEN is not present on any matching line.
# ----------------------------------------------------------------------
config_rm() {
    local param="$1" token="$2" file="$3"

    if rq -q "^\s*$param\b" "$file"; then
        local suffix=".backup.$(date +%F_%H%M%S_%N)"
        $sudo perl -i"$suffix" -s -I "$dir" "$dir/config_rm.pl" \
            -- -param="$param" -token="$token" "$file"
    fi
}

# ----------------------------------------------------------------------
# cleanup_backups – Remove old backup files generated by the editing functions.
#
# Usage: cleanup_backups [directory] [pattern]
#   directory: where to look for backup files (default: current directory)
#   pattern:   glob pattern matching backup files (default: *.backup.*)
#
# Policy:
#   - Keep all files from the last 7 days.
#   - Keep the 10 most recent files overall (by modification time).
#   - Delete any other file older than 30 days.
# ----------------------------------------------------------------------
cleanup_backups() {
    local dir="${1:-.}"
    local pattern="${2:-*.backup.*}"
    local now=$(date +%s)
    local week=$((7 * 86400))
    local month=$((30 * 86400))
    local keep_count=10

    # Collect all matching files with their mtime (seconds since epoch).
    local files=()
    while IFS= read -r -d '' entry; do
        files+=("$entry")
    done < <(find "$dir" -maxdepth 1 -type f -name "$pattern" -printf "%T@ %p\0" | sort -n)

    local total=${#files[@]}
    for (( i=0; i<total; i++ )); do
        local line="${files[i]}"
        local ts="${line%% *}"
        local file="${line#* }"
        local age=$((now - ts))
        local newer=$((total - i - 1))

        # Keep if younger than 7 days, or among the 10 most recent.
        if (( age < week )) || (( newer < keep_count )); then
            continue
        fi

        # Delete if older than 30 days and not protected.
        if (( age > month )); then
        (
            set -x
            $sudo rm -f "$file"
        )
        fi
    done
}

